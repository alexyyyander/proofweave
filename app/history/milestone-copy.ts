import type { HistoryMilestone } from "./HistoryTimeline";

/**
 * Editorial copy for the history milestones. Milestone prose is content, not
 * interface chrome, so it lives beside the record instead of in the shared
 * dictionary. Untranslated milestones fall back to the English source.
 */
export type MilestoneCopy = Partial<Pick<HistoryMilestone, "title" | "summary" | "shortTitle" | "evidence" | "aiRole" | "humanRole" | "significance" | "boundary">> & {
  sourceLabels?: readonly string[];
  reproduction?: Partial<NonNullable<HistoryMilestone["reproduction"]>>;
};

export function localizeMilestones(milestones: readonly HistoryMilestone[], copy: Record<string, MilestoneCopy>): HistoryMilestone[] {
  return milestones.map((milestone) => {
    const translation = copy[milestone.number];
    if (!translation) return milestone;
    return {
      ...milestone,
      ...(translation.title ? { title: translation.title } : {}),
      ...(translation.summary ? { summary: translation.summary } : {}),
      ...(translation.shortTitle ? { shortTitle: translation.shortTitle } : {}),
      ...(translation.evidence ? { evidence: translation.evidence } : {}),
      ...(translation.aiRole ? { aiRole: translation.aiRole } : {}),
      ...(translation.humanRole ? { humanRole: translation.humanRole } : {}),
      ...(translation.significance ? { significance: translation.significance } : {}),
      ...(translation.boundary ? { boundary: translation.boundary } : {}),
      sources: milestone.sources.map((source, index) => ({
        ...source,
        label: translation.sourceLabels?.[index] ?? source.label,
      })),
      reproduction: milestone.reproduction
        ? { ...milestone.reproduction, ...translation.reproduction }
        : milestone.reproduction,
    };
  });
}

